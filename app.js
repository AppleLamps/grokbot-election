/* Apple Lamps Grok Bot Election Analysis: vanilla JS, no dependencies.
   Loads data/results.json (generated by model/scripts/export_site_data.py from the model outputs)
   and drives the hero summary, scenario panel, in-browser SVG seat charts, comparison table and
   the sortable/filterable/searchable Senate race table. */
(function () {
  "use strict";

  var DATA_URL = "data/results.json"; // relative to index.html, works on any static host
  var SVGNS = "http://www.w3.org/2000/svg";
  var COLORS = { d: "#2563eb", dDark: "#1d4ed8", r: "#dc2626", rDark: "#b91c1c", ink: "#0f172a", ink2: "#334155", muted: "#475569", line: "#e2e8f0", accent: "#0f766e" };
  // Short labels used in charts (full labels come from results.json)
  var SHORT = {
    unbiased: { title: "Polls unbiased", sub: "Error centered on zero" },
    pres_style_D_overstatement: { title: "Polls overstate Dems by 3", sub: "2016/20/24-style" },
    r_overstatement_2025: { title: "Polls overstate Reps by 6", sub: "2025-style" }
  };

  var state = {
    data: null,
    scenario: "unbiased",
    sortKey: "p_unbiased",
    sortDir: "desc",
    search: "",
    holder: "",
    competitive: false
  };

  // ---------- formatting helpers ----------
  function pct(p) {
    if (p === null || p === undefined || isNaN(p)) return "\u2013";
    if (p >= 0.9995) return ">99.9%";
    if (p <= 0.0005) return "<0.1%";
    return (p * 100).toFixed(1) + "%";
  }
  function pct0(p) { // whole-number percent for big headline numbers
    if (p >= 0.995) return ">99%";
    if (p <= 0.005) return "<1%";
    return Math.round(p * 100) + "%";
  }
  // Tipping-point share: one consistent format (one decimal; anything under 0.05% shows as <0.1%)
  function tipPct(p) {
    if (p === null || p === undefined || isNaN(p)) return "\u2013";
    if (p < 0.0005) return "<0.1%";
    return (p * 100).toFixed(1) + "%";
  }
  function margin(m) {
    if (m === null || m === undefined || isNaN(m)) return "\u2013";
    if (Math.abs(m) < 0.05) return "EVEN";
    return (m > 0 ? "D+" : "R+") + Math.abs(m).toFixed(1);
  }
  function marginClass(m) { return m === null || m === undefined || Math.abs(m) < 0.05 ? "" : (m > 0 ? "d" : "r"); }
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  // Escape text and wrap every case-insensitive occurrence of q in <mark>
  function mark(text, q) {
    text = String(text == null ? "" : text);
    if (!q) return esc(text);
    var lower = text.toLowerCase(), out = "", i = 0, j;
    while ((j = lower.indexOf(q, i)) !== -1) {
      out += esc(text.slice(i, j)) + "<mark>" + esc(text.slice(j, j + q.length)) + "</mark>";
      i = j + q.length;
    }
    return out + esc(text.slice(i));
  }
  function $(sel, root) { return (root || document).querySelector(sel); }
  function $all(sel, root) { return Array.prototype.slice.call((root || document).querySelectorAll(sel)); }
  function setField(name, html) { $all('[data-field="' + name + '"]').forEach(function (el) { el.innerHTML = html; }); }
  function setWidth(el, frac) { if (el) el.style.width = Math.max(0, Math.min(1, frac)) * 100 + "%"; }
  function setBar(name, frac) { setWidth($('[data-bar="' + name + '"]'), frac); }

  // Probability pill: discrete diverging scale, neutral near 50%, more saturated for stronger favourites.
  // Every background/text pair below meets WCAG AA (>= 4.5:1).
  var BUCKETS = [
    { min: 0.95, bg: "#1e3a8a", fg: "#ffffff", label: "Solid D" },
    { min: 0.80, bg: "#2563eb", fg: "#ffffff", label: "Likely D" },
    { min: 0.60, bg: "#bfdbfe", fg: "#1e3a8a", label: "Lean D" },
    { min: 0.40, bg: "#e5e7eb", fg: "#111827", label: "Toss-up" },
    { min: 0.20, bg: "#fecaca", fg: "#7f1d1d", label: "Lean R" },
    { min: 0.05, bg: "#dc2626", fg: "#ffffff", label: "Likely R" },
    { min: -1, bg: "#991b1b", fg: "#ffffff", label: "Solid R" }
  ];
  function bucket(p) { for (var i = 0; i < BUCKETS.length; i++) if (p >= BUCKETS[i].min) return BUCKETS[i]; return BUCKETS[BUCKETS.length - 1]; }
  function pill(p) {
    if (p === null || p === undefined) return "\u2013";
    var b = bucket(p);
    return '<span class="pill" style="background:' + b.bg + ";color:" + b.fg + '" title="' + b.label + '">' + pct(p) + "</span>";
  }

  function renderPillLegend() {
    var ranges = ["\u226595%", "80\u201395%", "60\u201380%", "40\u201360%", "20\u201340%", "5\u201320%", "<5%"];
    $("#pill-legend").innerHTML = '<span class="pl-lbl">P(D) color key:</span>' + BUCKETS.map(function (b, i) {
      return '<span class="pl-item"><span class="pl-sw" style="background:' + b.bg + '"></span>' + b.label + ' <span class="pl-r">' + ranges[i] + "</span></span>";
    }).join("");
  }

  function scenarioByKey(key) {
    var list = state.data.scenarios;
    for (var i = 0; i < list.length; i++) if (list[i].key === key) return list[i];
    return list[0];
  }

  // ---------- tiny SVG helper ----------
  function el(name, attrs, text) {
    var n = document.createElementNS(SVGNS, name);
    for (var k in attrs) if (attrs.hasOwnProperty(k)) n.setAttribute(k, attrs[k]);
    if (text !== undefined) n.textContent = text;
    return n;
  }
  function chartWidth(container) { return Math.max(280, Math.floor(container.clientWidth || 520)); }

  // ---------- seat-range chart: one row per scenario (80% range bar + mean/median dot) ----------
  function drawSeatChart(container, cfg) {
    var W = chartWidth(container), padL = 4, padR = 4, rowH = 78, top = 2, axisH = 36;
    var H = top + rowH * cfg.rows.length + axisH;
    var x = function (v) { return padL + (v - cfg.min) / (cfg.max - cfg.min) * (W - padL - padR); };
    var svg = el("svg", { width: W, height: H, viewBox: "0 0 " + W + " " + H, "aria-hidden": "true", focusable: "false" });

    // majority-side background
    var plotTop = top, plotBot = top + rowH * cfg.rows.length;
    svg.appendChild(el("rect", { x: x(cfg.min), y: plotTop, width: x(cfg.threshold) - x(cfg.min), height: plotBot - plotTop, fill: "#fef2f2" }));
    svg.appendChild(el("rect", { x: x(cfg.threshold), y: plotTop, width: x(cfg.max) - x(cfg.threshold), height: plotBot - plotTop, fill: "#eff6ff" }));

    // gridlines + axis ticks
    cfg.ticks.forEach(function (t) {
      svg.appendChild(el("line", { x1: x(t), x2: x(t), y1: plotTop, y2: plotBot, stroke: "#e2e8f0", "stroke-width": 1 }));
      var anchor = t === cfg.ticks[0] ? "start" : t === cfg.ticks[cfg.ticks.length - 1] ? "end" : "middle";
      var lbl = el("text", { x: x(t), y: plotBot + 16, "text-anchor": anchor, "font-size": 12, fill: COLORS.muted }, String(t));
      if (t === cfg.majorityTick) { lbl.setAttribute("font-weight", "700"); lbl.setAttribute("fill", COLORS.ink); }
      svg.appendChild(lbl);
    });
    svg.appendChild(el("text", { x: padL, y: plotBot + 31, "font-size": 11.5, fill: COLORS.muted }, "\u2190 Republican majority"));
    svg.appendChild(el("text", { x: W - padR, y: plotBot + 31, "font-size": 11.5, fill: COLORS.muted, "text-anchor": "end" }, "Democratic majority \u2192"));

    // majority threshold line (drawn under the bars; text has a white halo)
    var tx = x(cfg.threshold);
    svg.appendChild(el("line", { x1: tx, x2: tx, y1: plotTop, y2: plotBot + 4, stroke: COLORS.ink, "stroke-width": 1.5, "stroke-dasharray": "4 3" }));

    cfg.rows.forEach(function (row, i) {
      var y0 = top + i * rowH, active = row.key === state.scenario;
      var g = el("g", { opacity: active ? 1 : 0.62 });
      g.appendChild(el("text", { x: padL + 6, y: y0 + 18, "font-size": 13.5, "font-weight": 700, fill: COLORS.ink }, SHORT[row.key] ? SHORT[row.key].title : row.label));
      var probTxt = row.pD >= 0.5 ? "D control " + pct0(row.pD) : "R control " + pct0(1 - row.pD - (row.pNone || 0));
      g.appendChild(el("text", { x: W - padR - 6, y: y0 + 18, "font-size": 13.5, "font-weight": 700, "text-anchor": "end", fill: row.pD >= 0.5 ? COLORS.dDark : COLORS.rDark }, probTxt));

      var by = y0 + 28, bh = 16, lo = Math.max(cfg.min, row.lo), hi = Math.min(cfg.max, row.hi);
      var clipId = "clip-" + container.id + "-" + i;
      var clip = el("clipPath", { id: clipId });
      clip.appendChild(el("rect", { x: x(lo), y: by, width: Math.max(2, x(hi) - x(lo)), height: bh, rx: 8 }));
      svg.appendChild(clip);
      if (active) g.appendChild(el("rect", { x: x(lo) - 3, y: by - 3, width: Math.max(6, x(hi) - x(lo) + 6), height: bh + 6, rx: 11, fill: "none", stroke: COLORS.ink, "stroke-width": 2 }));
      if (lo < cfg.threshold) g.appendChild(el("rect", { x: x(lo), y: by, width: Math.max(2, x(Math.min(hi, cfg.threshold)) - x(lo)), height: bh, fill: COLORS.r, "clip-path": "url(#" + clipId + ")" }));
      if (hi > cfg.threshold) g.appendChild(el("rect", { x: x(Math.max(lo, cfg.threshold)), y: by, width: Math.max(2, x(hi) - x(Math.max(lo, cfg.threshold))), height: bh, fill: COLORS.d, "clip-path": "url(#" + clipId + ")" }));
      var mx = x(Math.max(cfg.min, Math.min(cfg.max, row.mid)));
      g.appendChild(el("circle", { cx: mx, cy: by + bh / 2, r: 6.5, fill: "#fff", stroke: COLORS.ink, "stroke-width": 2.5 }));
      g.appendChild(el("text", { x: padL + 6, y: by + bh + 17, "font-size": 12, fill: COLORS.ink2 }, row.midLabel + " \u00b7 80% range " + row.lo + "\u2013" + row.hi));
      svg.appendChild(g);
      if (i < cfg.rows.length - 1) svg.appendChild(el("line", { x1: padL, x2: W - padR, y1: y0 + rowH, y2: y0 + rowH, stroke: "#ffffff", "stroke-width": 2 }));
    });

    container.innerHTML = "";
    container.appendChild(svg);
    container.setAttribute("aria-label", cfg.aria);
  }

  function renderSeatCharts() {
    var sc = state.data.scenarios;
    var senateRows = sc.map(function (s) {
      return { key: s.key, label: s.label, lo: s.senate.D_p10, hi: s.senate.D_p90, mid: s.senate.D_mean, midLabel: "avg " + s.senate.D_mean.toFixed(1), pD: s.senate.p_D, pNone: s.senate.p_none };
    });
    var houseRows = sc.map(function (s) {
      return { key: s.key, label: s.label, lo: s.house.D_p10, hi: s.house.D_p90, mid: s.house.D_median, midLabel: "median " + s.house.D_median, pD: s.house.p_D };
    });
    function aria(rows, unit) {
      return rows.map(function (r) { return r.label + ": " + unit + " 80% range " + r.lo + " to " + r.hi + ", " + r.midLabel + ", Democratic control " + pct(r.pD); }).join(". ");
    }
    drawSeatChart($("#chart-senate"), { rows: senateRows, min: 42, max: 60, threshold: 50.5, majorityTick: 51, ticks: [42, 45, 48, 51, 54, 57, 60], aria: "Senate Democratic plus allied independent seats. " + aria(senateRows, "seats") });
    drawSeatChart($("#chart-house"), { rows: houseRows, min: 200, max: 300, threshold: 217.5, majorityTick: 218, ticks: [200, 218, 240, 260, 280, 300], aria: "House Democratic seats. " + aria(houseRows, "seats") });
  }

  // ---------- per-race dot chart ----------
  var MARKERS = { unbiased: "circle", pres_style_D_overstatement: "square", r_overstatement_2025: "triangle" };
  function marker(shape, cx, cy, size, attrs) {
    var n;
    if (shape === "square") n = el("rect", { x: cx - size, y: cy - size, width: size * 2, height: size * 2, rx: 1.5 });
    else if (shape === "triangle") n = el("path", { d: "M" + cx + "," + (cy - size * 1.2) + "L" + (cx + size * 1.15) + "," + (cy + size * 0.9) + "L" + (cx - size * 1.15) + "," + (cy + size * 0.9) + "Z" });
    else n = el("circle", { cx: cx, cy: cy, r: size });
    for (var k in attrs) n.setAttribute(k, attrs[k]);
    return n;
  }
  function renderRaceChart() {
    var container = $("#chart-races");
    var keys = state.data.scenarios.map(function (s) { return s.key; });
    var races = state.data.senate_races.filter(function (r) {
      return keys.some(function (k) { var p = r.p_dem[k]; return p >= 0.05 && p <= 0.95; });
    }).slice().sort(function (a, b) { return b.p_dem.unbiased - a.p_dem.unbiased; });

    var W = chartWidth(container), narrow = W < 480;
    var labelW = narrow ? 96 : 150, padR = 14, rowH = 28, top = 26, H = top + rowH * races.length + 28;
    var x = function (p) { return labelW + p * (W - labelW - padR); };
    var svg = el("svg", { width: W, height: H, viewBox: "0 0 " + W + " " + H, "aria-hidden": "true", focusable: "false" });
    var plotBot = top + rowH * races.length;
    svg.appendChild(el("rect", { x: x(0), y: top, width: x(0.5) - x(0), height: plotBot - top, fill: "#fef2f2" }));
    svg.appendChild(el("rect", { x: x(0.5), y: top, width: x(1) - x(0.5), height: plotBot - top, fill: "#eff6ff" }));
    [0, 0.25, 0.5, 0.75, 1].forEach(function (t) {
      svg.appendChild(el("line", { x1: x(t), x2: x(t), y1: top, y2: plotBot, stroke: t === 0.5 ? COLORS.ink : "#e2e8f0", "stroke-width": t === 0.5 ? 1.5 : 1, "stroke-dasharray": t === 0.5 ? "4 3" : "" }));
      svg.appendChild(el("text", { x: x(t), y: plotBot + 17, "font-size": 12, "text-anchor": t === 0 ? "start" : t === 1 ? "end" : "middle", fill: t === 0.5 ? COLORS.ink : COLORS.muted, "font-weight": t === 0.5 ? 700 : 400 }, Math.round(t * 100) + "%"));
    });
    svg.appendChild(el("text", { x: x(0.25), y: top - 9, "font-size": 11.5, "text-anchor": "middle", fill: COLORS.rDark, "font-weight": 600 }, narrow ? "R favored" : "\u2190 Republican favored"));
    svg.appendChild(el("text", { x: x(0.75), y: top - 9, "font-size": 11.5, "text-anchor": "middle", fill: COLORS.dDark, "font-weight": 600 }, narrow ? "D favored" : "Democrat favored \u2192"));

    races.forEach(function (r, i) {
      var cy = top + i * rowH + rowH / 2;
      if (i % 2 === 1) svg.insertBefore(el("rect", { x: 0, y: cy - rowH / 2, width: labelW - 6, height: rowH, fill: "#f8fafc" }), svg.firstChild);
      svg.appendChild(el("text", { x: 4, y: cy + 4, "font-size": 13, fill: COLORS.ink, "font-weight": 600 }, narrow ? r.state + (r.seat === "special" ? "*" : "") : r.state_name + (r.seat === "special" ? " (sp.)" : "")));
      var ps = keys.map(function (k) { return r.p_dem[k]; });
      var mn = Math.min.apply(null, ps), mxp = Math.max.apply(null, ps);
      svg.appendChild(el("line", { x1: x(mn), x2: x(mxp), y1: cy, y2: cy, stroke: "#94a3b8", "stroke-width": 2 }));
      keys.forEach(function (k) {
        if (k === state.scenario) return;
        svg.appendChild(marker(MARKERS[k], x(r.p_dem[k]), cy, 4.5, { fill: "#fff", stroke: "#64748b", "stroke-width": 1.75 }));
      });
      var p = r.p_dem[state.scenario];
      var m = marker(MARKERS[state.scenario], x(p), cy, 7, { fill: p >= 0.5 ? COLORS.d : COLORS.r, stroke: "#fff", "stroke-width": 1.5 });
      var t = el("title", {}, r.state_name + ": " + pct(p) + " Democratic-side win chance (" + (SHORT[state.scenario] || {}).title + ")");
      m.appendChild(t);
      svg.appendChild(m);
    });
    container.innerHTML = "";
    container.appendChild(svg);
    container.setAttribute("aria-label", "Democratic-side win probability by competitive Senate race, selected scenario " + scenarioByKey(state.scenario).label + ": " +
      races.map(function (r) { return r.state_name + " " + pct(r.p_dem[state.scenario]); }).join(", "));

    // legend (HTML)
    $("#race-chart-legend").innerHTML = state.data.scenarios.map(function (s) {
      var on = s.key === state.scenario;
      var sz = 14, sh = MARKERS[s.key];
      var shape = sh === "square" ? '<rect x="2" y="2" width="10" height="10" rx="1.5"/>' : sh === "triangle" ? '<path d="M7,1L13,12L1,12Z"/>' : '<circle cx="7" cy="7" r="5.5"/>';
      return '<span class="lg' + (on ? " on" : "") + '"><svg width="' + sz + '" height="' + sz + '" viewBox="0 0 14 14"><g fill="' + (on ? COLORS.ink : "#fff") + '" stroke="' + (on ? COLORS.ink : "#64748b") + '" stroke-width="1.75">' + shape + "</g></svg>" +
        esc(SHORT[s.key].title) + (on ? " (selected, colored by favorite)" : "") + "</span>";
    }).join("");
  }

  // ---------- hero "at a glance" (always the unbiased base case) ----------
  function renderGlance() {
    var s = scenarioByKey("unbiased");
    $('[data-glance="senate-pD"]').textContent = pct0(s.senate.p_D);
    $('[data-glance="senate-pR"]').textContent = pct0(s.senate.p_R);
    $('[data-glance="house-pD"]').textContent = pct0(s.house.p_D);
    $('[data-glance="house-pR"]').textContent = pct0(s.house.p_R);
    setWidth($('[data-glance-bar="senate-d"]'), s.senate.p_D);
    setWidth($('[data-glance-bar="senate-n"]'), s.senate.p_none);
    setWidth($('[data-glance-bar="senate-r"]'), s.senate.p_R);
    setWidth($('[data-glance-bar="house-d"]'), s.house.p_D);
    setWidth($('[data-glance-bar="house-r"]'), s.house.p_R);
  }

  // ---------- scenario panel ----------
  function renderScenario() {
    var s = scenarioByKey(state.scenario);
    $all(".scenario-tabs [role=tab]").forEach(function (b) {
      var on = b.getAttribute("data-scenario") === s.key;
      b.setAttribute("aria-selected", on ? "true" : "false");
      b.tabIndex = on ? 0 : -1;
      if (on) $("#scenario-panel").setAttribute("aria-labelledby", b.id);
    });
    $("#scenario-desc").textContent = s.description + " " + s.sims.toLocaleString("en-US") + " simulations.";

    var se = s.senate, ho = s.house;
    setField("senate-pD", pct(se.p_D));
    setField("senate-pR", pct(se.p_R));
    var note = $('[data-field="senate-none"]');
    if (se.p_none >= 0.0005) {
      note.innerHTML = '<span class="swatch n" aria-hidden="true"></span>No clear majority (depends on independents\u2019 caucus choice): <strong>' + pct(se.p_none) + "</strong>";
      note.hidden = false;
    } else { note.hidden = true; }
    setField("senate-mean", se.D_mean.toFixed(1));
    setField("senate-range", se.D_p10 + "\u2013" + se.D_p90);
    setBar("senate-d", se.p_D); setBar("senate-n", se.p_none); setBar("senate-r", se.p_R);
    setField("senate-tip", tipChips(se.tipping, true));

    setField("house-pD", pct(ho.p_D));
    setField("house-pR", pct(ho.p_R));
    var hb = state.data.baseline && state.data.baseline.house;
    var need = hb ? 218 - hb.D : null;
    var hn = $('[data-field="house-need"]');
    if (need > 0) { hn.innerHTML = "Democrats hold " + hb.D + " seats today, so they need a net gain of <strong>" + need + "</strong> to reach 218."; hn.hidden = false; }
    else hn.hidden = true;
    setField("house-median", String(ho.D_median));
    setField("house-range", ho.D_p10 + "\u2013" + ho.D_p90);
    setBar("house-d", ho.p_D); setBar("house-r", ho.p_R);
    setField("house-tip", tipChips(ho.tipping, false));

    $all("#compare-table tbody tr").forEach(function (tr) {
      var on = tr.getAttribute("data-key") === s.key;
      tr.classList.toggle("active", on);
      if (on) tr.setAttribute("aria-current", "true"); else tr.removeAttribute("aria-current");
    });
    renderSeatCharts();
    renderRaceChart();
    renderRaces(); // update highlighted column
  }

  function tipChips(list, isSenate) {
    if (!list || !list.length) return "\u2013";
    var names = {};
    if (isSenate) state.data.senate_races.forEach(function (r) { names[r.state] = r.state_name; });
    return list.map(function (t) {
      var label = isSenate && names[t[0]] ? names[t[0]] : t[0];
      return '<span class="tip-chip" title="Tipping point in ' + tipPct(t[1]) + ' of simulations"><span class="tip-name">' +
        esc(label) + '</span><span class="tip-val">' + tipPct(t[1]) + "</span></span>";
    }).join("");
  }

  function renderCompare() {
    var tbody = $("#compare-table tbody");
    tbody.innerHTML = state.data.scenarios.map(function (s) {
      var sh = SHORT[s.key] || { title: s.label, sub: "" };
      return '<tr data-key="' + esc(s.key) + '">' +
        '<th scope="row"><span class="sc-title">' + esc(sh.title) + '</span><span class="sc-sub">' + esc(sh.sub) + "</span></th>" +
        '<td class="num d"><strong>' + pct(s.senate.p_D) + "</strong></td>" +
        '<td class="num r"><strong>' + pct(s.senate.p_R) + "</strong></td>" +
        '<td class="num">' + s.senate.D_mean.toFixed(1) + ' <span class="rng">(' + s.senate.D_p10 + "\u2013" + s.senate.D_p90 + ")</span></td>" +
        '<td class="num d"><strong>' + pct(s.house.p_D) + "</strong></td>" +
        '<td class="num">' + s.house.D_median + ' <span class="rng">(' + s.house.D_p10 + "\u2013" + s.house.D_p90 + ")</span></td></tr>";
    }).join("");
  }

  // ---------- race table ----------
  function sortValue(r, key) {
    if (key.indexOf("p_") === 0 && key !== "poll_margin_d") return r.p_dem[key.slice(2)];
    if (key === "state") return r.state_name;
    return r[key];
  }

  function filteredRaces() {
    var q = state.search.trim().toLowerCase();
    var keys = state.data.scenarios.map(function (s) { return s.key; });
    return state.data.senate_races.filter(function (r) {
      if (state.holder && r.holder !== state.holder) return false;
      if (state.competitive) {
        var any = keys.some(function (k) { var p = r.p_dem[k]; return p >= 0.1 && p <= 0.9; });
        if (!any) return false;
      }
      if (q) {
        var hay = [r.state, r.state_name, r.dem_side_candidate, r.rep_candidate, r.seat === "special" ? "special election" : "regular"].join(" | ").toLowerCase();
        if (hay.indexOf(q) === -1) return false;
      }
      return true;
    }).sort(function (a, b) {
      var va = sortValue(a, state.sortKey), vb = sortValue(b, state.sortKey);
      var na = va === null || va === undefined, nb = vb === null || vb === undefined;
      if (na && nb) return a.state_name.localeCompare(b.state_name);
      if (na) return 1;   // missing values always last
      if (nb) return -1;
      var c = typeof va === "string" ? va.localeCompare(vb) : va - vb;
      if (c === 0) c = a.state_name.localeCompare(b.state_name) * (state.sortDir === "asc" ? 1 : -1);
      return state.sortDir === "asc" ? c : -c;
    });
  }

  function renderRaces() {
    if (!state.data) return;
    var q = state.search.trim().toLowerCase();
    var rows = filteredRaces();
    var keys = state.data.scenarios.map(function (s) { return s.key; });
    var tbody = $("#race-table tbody");
    if (!rows.length) {
      tbody.innerHTML = '<tr><td class="empty" colspan="9">No races match these filters.</td></tr>';
    } else {
      tbody.innerHTML = rows.map(function (r) {
        var seat = r.seat === "special" ? "Special election" : "Regular";
        var probs = keys.map(function (k) {
          var hl = k === state.scenario ? " hl" : "";
          return '<td class="num' + hl + '">' + pill(r.p_dem[k]) + "</td>";
        }).join("");
        var poll = r.poll_margin_d === null || r.poll_margin_d === undefined ?
          '<span class="no-poll" title="No public polling found for this race; the model uses fundamentals only">No polls</span>' :
          '<span class="' + marginClass(r.poll_margin_d) + '">' + margin(r.poll_margin_d) + '</span> <span class="n-polls" title="' + r.poll_sources + " poll" + (r.poll_sources === 1 ? "" : "s") + ' in the average">(' + r.poll_sources + ")</span>";
        var partyName = { D: "Democrat", R: "Republican", I: "Independent" };
        return "<tr>" +
          '<th scope="row" class="state-cell"><strong>' + mark(r.state_name, q) + '</strong><span class="sub">' + mark(r.state, q) + " \u00b7 " + mark(seat, q) + "</span></th>" +
          '<td><span class="party-tag ' + esc(r.holder) + '" title="Seat currently held by ' + (partyName[r.holder] || r.holder) + '">' + esc(r.holder) + "</span></td>" +
          '<td class="cand"><span class="c"><span class="party-tag ' + esc(r.dem_side_party) + '">' + esc(r.dem_side_party) + "</span> <span class=\"cn\">" + mark(r.dem_side_candidate, q) + "</span></span>" +
          '<span class="c"><span class="party-tag R">R</span> <span class="cn">' + mark(r.rep_candidate, q) + "</span></span></td>" +
          '<td class="num mono">' + poll + "</td>" +
          '<td class="num mono"><span class="' + marginClass(r.est_margin) + '">' + margin(r.est_margin) + "</span></td>" +
          probs +
          '<td class="num mono">' + tipPct(r.tipping_freq) + "</td></tr>";
      }).join("");
    }
    var countTxt = "Showing " + rows.length + " of " + state.data.senate_races.length + " races";
    if (q) countTxt += " matching \u201c" + state.search.trim() + "\u201d in state or candidate names (matches highlighted)";
    $("#race-count").textContent = countTxt + ".";
    $all("#race-table thead th").forEach(function (th) {
      var key = th.getAttribute("data-sort");
      th.setAttribute("aria-sort", key === state.sortKey ? (state.sortDir === "asc" ? "ascending" : "descending") : "none");
      th.classList.toggle("hl", th.getAttribute("data-col") === state.scenario);
    });
  }

  // ---------- wiring ----------
  function selectScenario(key) {
    if (state.scenario === key) return;
    state.scenario = key;
    renderScenario();
  }
  function bindEvents() {
    var buttons = $all(".scenario-tabs [role=tab]");
    buttons.forEach(function (b, i) {
      b.addEventListener("click", function () { if (state.data) selectScenario(b.getAttribute("data-scenario")); });
      b.addEventListener("keydown", function (e) { // arrow-key navigation for the tablist (automatic activation)
        var n = buttons.length, idx = null;
        if (e.key === "ArrowRight" || e.key === "ArrowDown") idx = (i + 1) % n;
        else if (e.key === "ArrowLeft" || e.key === "ArrowUp") idx = (i - 1 + n) % n;
        else if (e.key === "Home") idx = 0;
        else if (e.key === "End") idx = n - 1;
        if (idx === null) return;
        e.preventDefault();
        buttons[idx].focus(); buttons[idx].click();
      });
    });
    $all("#race-table thead th").forEach(function (th) {
      var key = th.getAttribute("data-sort");
      $("button", th).addEventListener("click", function () {
        if (state.sortKey === key) state.sortDir = state.sortDir === "asc" ? "desc" : "asc";
        else { state.sortKey = key; state.sortDir = th.classList.contains("num") ? "desc" : "asc"; }
        renderRaces();
      });
    });
    $("#race-search").addEventListener("input", function (e) { state.search = e.target.value; renderRaces(); });
    $("#race-holder").addEventListener("change", function (e) { state.holder = e.target.value; renderRaces(); });
    $("#race-competitive").addEventListener("change", function (e) { state.competitive = e.target.checked; renderRaces(); });

    var lastW = window.innerWidth, t;
    window.addEventListener("resize", function () {
      if (!state.data || window.innerWidth === lastW) return;
      lastW = window.innerWidth;
      clearTimeout(t);
      t = setTimeout(function () { renderSeatCharts(); renderRaceChart(); }, 120);
    });
  }

  function applyBaseline(d) {
    var b = d.baseline;
    if (!b) return;
    var dds = $all("#baseline dd");
    if (dds.length >= 5) {
      dds[0].innerHTML = '<span class="r">' + b.senate.R + ' R</span> &middot; <span class="d">' + b.senate.D + ' D</span> &middot; <span class="i">' + b.senate.I + " I</span>";
      dds[1].textContent = b.senate.up;
      dds[2].innerHTML = '<span class="r">' + b.house.R + ' R</span> &middot; <span class="d">' + b.house.D + " D</span>";
      dds[3].textContent = "D+" + d.generic_ballot_d;
      dds[4].textContent = d.scenarios[0].sims.toLocaleString("en-US");
    }
  }

  function showError(err) {
    var msg = document.createElement("div");
    msg.className = "load-error";
    msg.setAttribute("role", "alert");
    var fileHint = location.protocol === "file:" ?
      " Browsers block loading local JSON from file:// pages. Serve the folder instead, e.g. <code>python3 -m http.server</code> and open http://localhost:8000." : "";
    msg.innerHTML = "<strong>Couldn't load the model results</strong> (" + esc(err && err.message ? err.message : err) + ")." + fileHint +
      ' The full results are also in <a href="model/output/REPORT.md">REPORT.md</a>.';
    $("#scenarios .wrap").insertBefore(msg, $("#scenarios .scenario-tabs"));
    if (window.console) console.error(err);
  }

  function init() {
    bindEvents();
    fetch(DATA_URL, { cache: "no-cache" })
      .then(function (res) {
        if (!res.ok) throw new Error("HTTP " + res.status + " for " + DATA_URL);
        return res.json();
      })
      .then(function (data) {
        if (!data || !data.scenarios || !data.senate_races) throw new Error("results.json is missing expected fields");
        state.data = data;
        applyBaseline(data);
        renderGlance();
        renderPillLegend();
        renderCompare();
        renderScenario();
        document.documentElement.classList.add("loaded");
      })
      .catch(showError);
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
