/* Apple Lamps Grok Bot Election Analysis: vanilla JS, no dependencies.
   Loads data/results.json (generated by model/scripts/export_site_data.py from the model outputs)
   and drives the scenario panel, comparison table and sortable/filterable Senate race table. */
(function () {
  "use strict";

  var DATA_URL = "data/results.json"; // relative to index.html, works on any static host
  var state = {
    data: null,
    scenario: "unbiased",
    sortKey: "p_unbiased",
    sortDir: "desc",
    search: "",
    holder: "",
    competitive: false
  };

  // ---------- formatting helpers ----------
  function pct(p) {
    if (p === null || p === undefined || isNaN(p)) return "\u2013";
    if (p >= 0.9995) return ">99.9%";
    if (p <= 0.0005) return "<0.1%";
    return (p * 100).toFixed(1) + "%";
  }
  function margin(m) {
    if (m === null || m === undefined || isNaN(m)) return "\u2013";
    if (Math.abs(m) < 0.05) return "EVEN";
    return (m > 0 ? "D+" : "R+") + Math.abs(m).toFixed(1);
  }
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  function $(sel, root) { return (root || document).querySelector(sel); }
  function $all(sel, root) { return Array.prototype.slice.call((root || document).querySelectorAll(sel)); }
  function setField(name, html) { $all('[data-field="' + name + '"]').forEach(function (el) { el.innerHTML = html; }); }
  function setBar(name, frac) { var el = $('[data-bar="' + name + '"]'); if (el) el.style.width = Math.max(0, Math.min(1, frac)) * 100 + "%"; }

  // Probability pill colour: blue when D favoured, red when R favoured, intensity by confidence.
  function pillStyle(p) {
    if (p === null || p === undefined) return "";
    var strength = Math.abs(p - 0.5) * 2; // 0..1
    var a = 0.12 + 0.78 * strength;
    var rgb = p >= 0.5 ? "37,99,235" : "220,38,38";
    var fg = a > 0.55 ? "#fff" : (p >= 0.5 ? "#1e3a8a" : "#7f1d1d");
    return "background:rgba(" + rgb + "," + a.toFixed(2) + ");color:" + fg;
  }

  function scenarioByKey(key) {
    var list = state.data.scenarios;
    for (var i = 0; i < list.length; i++) if (list[i].key === key) return list[i];
    return list[0];
  }

  // ---------- range strip (80% interval vs majority line) ----------
  function drawStrip(el, opts) {
    var span = opts.max - opts.min;
    function pos(v) { return ((v - opts.min) / span) * 100; }
    if (!el.firstChild) {
      var html = '<div class="track"></div><div class="band"></div><div class="mid"></div>' +
        '<div class="maj" style="left:' + pos(opts.majority) + '%"></div>';
      opts.ticks.forEach(function (t) { html += '<span class="tick" style="left:' + pos(t) + '%">' + t + "</span>"; });
      el.innerHTML = html;
    }
    var band = $(".band", el), mid = $(".mid", el);
    var lo = Math.max(opts.min, opts.lo), hi = Math.min(opts.max, opts.hi);
    band.style.left = pos(lo) + "%";
    band.style.width = Math.max(1, pos(hi) - pos(lo)) + "%";
    mid.style.left = pos(Math.max(opts.min, Math.min(opts.max, opts.mid))) + "%";
  }

  // ---------- scenario panel ----------
  function renderScenario() {
    var s = scenarioByKey(state.scenario);
    $all(".scenario-buttons button").forEach(function (b) {
      var on = b.getAttribute("data-scenario") === s.key;
      b.setAttribute("aria-selected", on ? "true" : "false");
      b.tabIndex = on ? 0 : -1;
    });
    $("#scenario-desc").textContent = s.description + " " + s.sims.toLocaleString("en-US") + " simulations.";

    var se = s.senate, ho = s.house;
    setField("senate-pD", pct(se.p_D));
    setField("senate-pR", pct(se.p_R));
    setField("senate-none", se.p_none >= 0.0005 ? "No clear majority (depends on independents' caucus choice): " + pct(se.p_none) : "&nbsp;");
    setField("senate-mean", se.D_mean.toFixed(1));
    setField("senate-range", se.D_p10 + "\u2013" + se.D_p90);
    setBar("senate-d", se.p_D); setBar("senate-n", se.p_none); setBar("senate-r", se.p_R);
    setField("senate-tip", tipChips(se.tipping, true));

    setField("house-pD", pct(ho.p_D));
    setField("house-pR", pct(ho.p_R));
    setField("house-median", String(ho.D_median));
    setField("house-range", ho.D_p10 + "\u2013" + ho.D_p90);
    setBar("house-d", ho.p_D); setBar("house-r", ho.p_R);
    setField("house-tip", tipChips(ho.tipping, false));

    drawStrip($('[data-strip="senate"]'), { min: 40, max: 62, majority: 50.5, lo: se.D_p10, hi: se.D_p90, mid: se.D_mean, ticks: [40, 45, 51, 55, 60] });
    drawStrip($('[data-strip="house"]'), { min: 180, max: 300, majority: 218, lo: ho.D_p10, hi: ho.D_p90, mid: ho.D_median, ticks: [180, 200, 218, 250, 300] });

    $all("#compare-table tbody tr").forEach(function (tr) {
      tr.classList.toggle("active", tr.getAttribute("data-key") === s.key);
    });
    renderRaces(); // update highlighted column
  }

  function tipChips(list, isSenate) {
    if (!list || !list.length) return "\u2013";
    var names = {};
    if (isSenate) state.data.senate_races.forEach(function (r) { names[r.state] = r.state_name; });
    return list.map(function (t) {
      var label = isSenate && names[t[0]] ? names[t[0]] : t[0];
      return '<span class="tip-chip" title="Tipping point in ' + (t[1] * 100).toFixed(1) + '% of simulations">' +
        esc(label) + " " + (t[1] * 100).toFixed(1) + "%</span>";
    }).join("");
  }

  function renderCompare() {
    var tbody = $("#compare-table tbody");
    tbody.innerHTML = state.data.scenarios.map(function (s) {
      return '<tr data-key="' + esc(s.key) + '">' +
        "<td>" + esc(s.label) + "</td>" +
        '<td class="d"><strong>' + pct(s.senate.p_D) + "</strong></td>" +
        '<td class="r"><strong>' + pct(s.senate.p_R) + "</strong></td>" +
        "<td>" + s.senate.D_mean.toFixed(1) + " (" + s.senate.D_p10 + "\u2013" + s.senate.D_p90 + ")</td>" +
        '<td class="d"><strong>' + pct(s.house.p_D) + "</strong></td>" +
        "<td>" + s.house.D_median + " (" + s.house.D_p10 + "\u2013" + s.house.D_p90 + ")</td></tr>";
    }).join("");
  }

  // ---------- race table ----------
  function sortValue(r, key) {
    if (key.indexOf("p_") === 0 && key !== "poll_margin_d") return r.p_dem[key.slice(2)];
    if (key === "state") return r.state_name;
    return r[key];
  }

  function filteredRaces() {
    var q = state.search.trim().toLowerCase();
    var keys = state.data.scenarios.map(function (s) { return s.key; });
    return state.data.senate_races.filter(function (r) {
      if (state.holder && r.holder !== state.holder) return false;
      if (state.competitive) {
        var any = keys.some(function (k) { var p = r.p_dem[k]; return p >= 0.1 && p <= 0.9; });
        if (!any) return false;
      }
      if (q) {
        var hay = [r.state, r.state_name, r.dem_side_candidate, r.rep_candidate, r.seat].join(" ").toLowerCase();
        if (hay.indexOf(q) === -1) return false;
      }
      return true;
    }).sort(function (a, b) {
      var va = sortValue(a, state.sortKey), vb = sortValue(b, state.sortKey);
      var na = va === null || va === undefined, nb = vb === null || vb === undefined;
      if (na && nb) return 0;
      if (na) return 1;   // missing values always last
      if (nb) return -1;
      var c = typeof va === "string" ? va.localeCompare(vb) : va - vb;
      return state.sortDir === "asc" ? c : -c;
    });
  }

  function renderRaces() {
    if (!state.data) return;
    var rows = filteredRaces();
    var keys = state.data.scenarios.map(function (s) { return s.key; });
    var tbody = $("#race-table tbody");
    if (!rows.length) {
      tbody.innerHTML = '<tr><td class="empty" colspan="9">No races match these filters.</td></tr>';
    } else {
      tbody.innerHTML = rows.map(function (r) {
        var seat = r.seat === "special" ? "Special election" : "Regular";
        var probs = keys.map(function (k) {
          var hl = k === state.scenario ? " hl" : "";
          return '<td class="num' + hl + '"><span class="pill" style="' + pillStyle(r.p_dem[k]) + '">' + pct(r.p_dem[k]) + "</span></td>";
        }).join("");
        return "<tr>" +
          '<td class="state-cell"><strong>' + esc(r.state_name) + '</strong><span class="sub">' + esc(r.state) + " \u00b7 " + seat + "</span></td>" +
          '<td><span class="party-tag ' + esc(r.holder) + '">' + esc(r.holder) + "</span></td>" +
          '<td class="cand"><span class="c"><span class="party-tag ' + esc(r.dem_side_party) + '">' + esc(r.dem_side_party) + "</span> " + esc(r.dem_side_candidate) + "</span>" +
          '<span class="c"><span class="party-tag R">R</span> ' + esc(r.rep_candidate) + "</span></td>" +
          '<td class="num mono">' + margin(r.poll_margin_d) + (r.poll_sources ? ' <span class="muted small">(' + r.poll_sources + ")</span>" : "") + "</td>" +
          '<td class="num mono">' + margin(r.est_margin) + "</td>" +
          probs +
          '<td class="num mono">' + (r.tipping_freq ? (r.tipping_freq * 100).toFixed(1) + "%" : "0%") + "</td></tr>";
      }).join("");
    }
    $("#race-count").textContent = "Showing " + rows.length + " of " + state.data.senate_races.length + " races.";
    $all("#race-table thead th").forEach(function (th) {
      var key = th.getAttribute("data-sort");
      th.setAttribute("aria-sort", key === state.sortKey ? (state.sortDir === "asc" ? "ascending" : "descending") : "none");
      th.classList.toggle("hl", th.getAttribute("data-col") === state.scenario);
    });
  }

  // ---------- wiring ----------
  function bindEvents() {
    var buttons = $all(".scenario-buttons button");
    buttons.forEach(function (b, i) {
      b.addEventListener("click", function () { state.scenario = b.getAttribute("data-scenario"); renderScenario(); });
      b.addEventListener("keydown", function (e) { // arrow-key navigation for the tablist
        var d = e.key === "ArrowRight" || e.key === "ArrowDown" ? 1 : e.key === "ArrowLeft" || e.key === "ArrowUp" ? -1 : 0;
        if (!d) return;
        e.preventDefault();
        var next = buttons[(i + d + buttons.length) % buttons.length];
        next.focus(); next.click();
      });
    });
    $all("#race-table thead th").forEach(function (th) {
      var key = th.getAttribute("data-sort");
      $("button", th).addEventListener("click", function () {
        if (state.sortKey === key) state.sortDir = state.sortDir === "asc" ? "desc" : "asc";
        else { state.sortKey = key; state.sortDir = th.classList.contains("num") ? "desc" : "asc"; }
        renderRaces();
      });
    });
    $("#race-search").addEventListener("input", function (e) { state.search = e.target.value; renderRaces(); });
    $("#race-holder").addEventListener("change", function (e) { state.holder = e.target.value; renderRaces(); });
    $("#race-competitive").addEventListener("change", function (e) { state.competitive = e.target.checked; renderRaces(); });
  }

  function applyBaseline(d) {
    var b = d.baseline;
    if (!b) return;
    var dds = $all("#baseline dd");
    if (dds.length >= 5) {
      dds[0].innerHTML = '<span class="r">' + b.senate.R + ' R</span> &middot; <span class="d">' + b.senate.D + ' D</span> &middot; <span class="i">' + b.senate.I + " I</span>";
      dds[1].textContent = b.senate.up;
      dds[2].innerHTML = '<span class="r">' + b.house.R + ' R</span> &middot; <span class="d">' + b.house.D + " D</span>";
      dds[3].textContent = "D+" + d.generic_ballot_d;
      dds[4].textContent = d.scenarios[0].sims.toLocaleString("en-US");
    }
  }

  function showError(err) {
    var msg = document.createElement("div");
    msg.className = "load-error";
    msg.setAttribute("role", "alert");
    var fileHint = location.protocol === "file:" ?
      " Browsers block loading local JSON from file:// pages. Serve the folder instead, e.g. <code>python3 -m http.server</code> and open http://localhost:8000." : "";
    msg.innerHTML = "<strong>Couldn't load the model results</strong> (" + esc(err && err.message ? err.message : err) + ")." + fileHint +
      ' The full results are also in <a href="model/output/REPORT.md">REPORT.md</a>.';
    $("#scenarios .wrap").insertBefore(msg, $("#scenarios .scenario-buttons"));
  }

  function init() {
    bindEvents();
    fetch(DATA_URL, { cache: "no-cache" })
      .then(function (res) {
        if (!res.ok) throw new Error("HTTP " + res.status + " for " + DATA_URL);
        return res.json();
      })
      .then(function (data) {
        if (!data || !data.scenarios || !data.senate_races) throw new Error("results.json is missing expected fields");
        state.data = data;
        applyBaseline(data);
        renderCompare();
        renderScenario();
      })
      .catch(showError);
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
